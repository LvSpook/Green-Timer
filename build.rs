//! Embeds the window/taskbar icon and version metadata straight into the
//! executable.
//!
//! Without this, only the Inno Setup installer applied an icon. The standalone
//! `GreenTimer.exe` from a release therefore showed the generic Windows
//! executable document icon in Explorer, on the desktop, in Alt-Tab, and had
//! blank file properties. Embedding the icon as a Win32 resource means the
//! single-file download is self-contained.

use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=green_timer.ico");
    println!("cargo:rerun-if-changed=build.rs");

    // Resources are meaningless (and rc.exe is unavailable) off Windows.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }

    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let script = out.join("green_timer.rc");
    let icon = root.join("green_timer.ico");

    std::fs::write(&script, resource_script(&icon))
        .unwrap_or_else(|err| panic!("could not write {}: {err}", script.display()));

    // `manifest_optional`: an icon is cosmetic, so a missing manifest is fine.
    embed_resource::compile(&script, embed_resource::NONE)
        .manifest_optional()
        .expect("failed to compile the Windows resource script (icon + version info)");
}

/// A single `.rc` covering the icon plus the strings Explorer shows on the
/// Details tab, so the exe is not an anonymous blob either.
fn resource_script(icon: &Path) -> String {
    let (major, minor, patch) = version_parts();
    let version = format!("{major}.{minor}.{patch}");
    let comma = format!("{major},{minor},{patch},0");

    // `rc.exe` wants doubled backslashes in a quoted path.
    let icon = icon.display().to_string().replace('\\', "\\\\");

    format!(
        r#"// Generated by build.rs - do not edit.
1 ICON "{icon}"

1 VERSIONINFO
FILEVERSION {comma}
PRODUCTVERSION {comma}
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "CompanyName", "Luke V"
            VALUE "FileDescription", "Green Timer"
            VALUE "FileVersion", "{version}"
            VALUE "InternalName", "GreenTimer"
            VALUE "LegalCopyright", "MIT License"
            VALUE "OriginalFilename", "GreenTimer.exe"
            VALUE "ProductName", "Green Timer"
            VALUE "ProductVersion", "{version}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#
    )
}

/// `CARGO_PKG_VERSION` as numeric components, ignoring any pre-release suffix.
fn version_parts() -> (u16, u16, u16) {
    let raw = std::env::var("CARGO_PKG_VERSION").unwrap_or_default();
    let mut parts = raw
        .split(['.', '-', '+'])
        .map(|part| part.parse::<u16>().unwrap_or(0));
    (
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
    )
}
